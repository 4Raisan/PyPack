"""Build self-contained launchers and a source ZIP from this checkout."""
import argparse
import base64
import hashlib
from pathlib import Path
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def build_unix(output):
    # Reuse the source launcher's interpreter discovery, then unpack into a
    # private temporary directory. Python performs cleanup even on interruption.
    source = (ROOT / "pypack-setup.sh").read_text(encoding="utf-8")
    discovery = source[source.index("find_python() {"):source.index('if [ "$#" -eq 0 ]; then')]
    payloads = {name: base64.b64encode((ROOT / name).read_bytes()).decode("ascii")
                for name in ("pypack_setup.py", "assets/pypack-icon.png", "LICENSE")}
    unpack = '''import base64, os, pathlib, signal, subprocess, sys, tempfile

def interrupted(signum, frame):
    raise SystemExit(128 + signum)

for name in ("SIGHUP", "SIGINT", "SIGTERM"):
    signum = getattr(signal, name, None)
    if signum is not None:
        signal.signal(signum, interrupted)
with tempfile.TemporaryDirectory(prefix="pypack-") as directory:
    root = pathlib.Path(directory)
'''
    for name, data in payloads.items():
        unpack += f'    target = root / {name!r}\n'
        unpack += '    target.parent.mkdir(parents=True, exist_ok=True)\n'
        unpack += f'    target.write_bytes(base64.b64decode({data!r}))\n'
    unpack += '''    args = sys.argv[1:] or ["--gui"]
    try:
        status = subprocess.call([sys.executable, str(root / "pypack_setup.py"), *args])
    except OSError as error:
        print(f"[PyPack] Could not start: {error}", file=sys.stderr)
        status = 1
    sys.exit(status if status >= 0 else 128 - status)
'''
    script = '#!/bin/sh\n# PyPack standalone launcher; generated by scripts/build_release.py.\nset -u\n'
    script += discovery + 'exec "$PY" - "$@" <<\'PYPACK_ASSETS\'\n' + unpack + 'PYPACK_ASSETS\n'
    for name in ("PyPack.sh", "PyPack.command"):
        path = output / name
        path.write_text(script, encoding="utf-8", newline="\n")
        path.chmod(0o755)


def build_windows(output):
    if sys.platform != "win32":
        raise RuntimeError("Build the Windows executable on Windows.")
    subprocess.run([
        sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
        "--onefile", "--console", "--hide-console", "hide-early", "--noupx",
        "--name", "PyPack", "--icon", str(ROOT / "assets/pypack.ico"),
        "--hidden-import", "tkinter", "--hidden-import", "tkinter.ttk",
        "--hidden-import", "tkinter.messagebox", "--hidden-import", "tkinter.filedialog",
        "--add-data", f"{ROOT / 'assets/pypack-icon.png'}:assets",
        "--add-data", f"{ROOT / 'pypack-bootstrap.ps1'}:.",
        "--add-data", f"{ROOT / 'LICENSE'}:.",
        "--distpath", str(output), "--workpath", str(ROOT / "build/pyinstaller"),
        "--specpath", str(ROOT / "build"), str(ROOT / "pypack_setup.py")
    ], cwd=ROOT, check=True)


def build_source(output):
    # Only version-controlled inputs belong in source downloads. Build after
    # committing changes so the source archive identifies a complete revision.
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    result = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True)
    with zipfile.ZipFile(output / f"PyPack-{version}-source.zip", "w", zipfile.ZIP_DEFLATED) as archive:
        for name in sorted(result.stdout.decode("utf-8").split("\0")):
            if name and not name.startswith(("releases/", "dist/", "build/")):
                path = ROOT / name
                if not path.is_file():
                    raise FileNotFoundError(f"Tracked source file is missing: {name}")
                info = zipfile.ZipInfo(f"PyPack-{version}-source/{name}", (1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                mode = 0o755 if name.endswith((".sh", ".command")) else 0o644
                info.external_attr = (0o100000 | mode) << 16
                archive.writestr(info, path.read_bytes())


def write_checksums(output):
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    names = ("PyPack.exe", "PyPack.sh", "PyPack.command", f"PyPack-{version}-source.zip")
    checksums = [f"{hashlib.sha256((output / name).read_bytes()).hexdigest()}  {name}"
                 for name in names if (output / name).is_file()]
    (output / "SHA256SUMS.txt").write_text("\n".join(checksums) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--windows", action="store_true", help="also build the Windows executable")
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    build_unix(output)
    if args.windows:
        build_windows(output)
    build_source(output)
    write_checksums(output)
    print(f"Built PyPack downloads in {output}")


if __name__ == "__main__":
    main()
